#!/usr/bin/env python3
"""Generate the ephemeris tables in lib/src/gen/ from Astronomy Engine (MIT, Don Cross).

  - vsop.dart   truncated VSOP87 series for Mercury..Neptune (heliocentric, ecliptic J2000)
  - moon.dart   the 104 solar-perturbation terms of the Montenbruck-Pfleger lunar theory
  - pluto.dart  Pluto heliocentric ecliptic J2000 every 20 days, 1799..2201 (from the
                engine's gravity simulation; the app interpolates)

Usage: PYTHONPATH=<dir with astronomy-engine> python3 tool/gen_tables.py
"""
import math, os, re, inspect
import astronomy.astronomy as A

OUT = os.path.join(os.path.dirname(__file__), '..', 'lib', 'astro', 'gen')
HEAD = '// GENERATED by tool/gen_tables.py from Astronomy Engine (MIT, (c) 2019-2023 Don Cross). Do not edit.\n'

def num(x):
    s = repr(float(x))
    return s

# ---- VSOP ----
lines = [HEAD, '// [planet][lon|lat|rad][power] = flat (amplitude, phase, frequency) triples.\n',
         '// Planet order: Mercury, Venus, Earth, Mars, Jupiter, Saturn, Uranus, Neptune.\n',
         'const List<List<List<List<double>>>> vsop = [\n']
for model in A._vsop:
    lines.append('  [\n')
    for formula in (model.lon, model.lat, model.rad):
        lines.append('    [\n')
        for series in formula.seriesList:
            flat = ','.join(num(v) for t in series.termList for v in t)
            lines.append(f'      [{flat}],\n')
        lines.append('    ],\n')
    lines.append('  ],\n')
lines.append('];\n')
open(os.path.join(OUT, 'vsop.dart'), 'w').write(''.join(lines))

# ---- Moon ----
src = inspect.getsource(A._CalcMoon)
terms = re.findall(r'# AddSol\(([^)]*)\)', src)
assert len(terms) == 104, len(terms)
rows = []
for t in terms:
    v = [float(x) for x in t.split(',')]
    rows.append('  ' + ','.join(num(x) if i < 4 else str(int(x)) for i, x in enumerate(v)) + ',')
open(os.path.join(OUT, 'moon.dart'), 'w').write(
    HEAD + '// Montenbruck-Pfleger lunar terms: (dLambda, dS, gam1C, sinPi, p, q, r, s) per row.\n'
    'const List<num> moonSol = [\n' + '\n'.join(rows) + '\n];\n')

# ---- Pluto ----
# VSOP ecliptic -> EQJ rotation used by the engine; invert it (transpose) to get back to ecliptic J2000.
R = [[1, 0.000000440360, -0.000000190919],
     [-0.000000479966, 0.917482137087, -0.397776982902],
     [0, 0.397776982902, 0.917482137087]]
def eqj_to_ecl(x, y, z):
    return [R[0][i]*x + R[1][i]*y + R[2][i]*z for i in range(3)]
t0 = A.Time.Make(1799, 1, 1, 0, 0, 0).tt
STEP = 20.0
N = int((A.Time.Make(2201, 1, 1, 0, 0, 0).tt - t0) / STEP) + 2
vals = []
for i in range(N):
    tm = A.Time._FromTerrestrialTime(t0 + i*STEP) if hasattr(A.Time, '_FromTerrestrialTime') else A.Time.FromTerrestrialTime(t0 + i*STEP)
    v = A.HelioVector(A.Body.Pluto, tm)
    vals.extend(eqj_to_ecl(v.x, v.y, v.z))
body = ',\n'.join(','.join(f'{x:.9f}' for x in vals[i:i+12]) for i in range(0, len(vals), 12))
open(os.path.join(OUT, 'pluto.dart'), 'w').write(
    HEAD + f'// Pluto heliocentric ecliptic J2000 (AU), x,y,z every {STEP:g} days from TT {t0!r} (days since J2000).\n'
    f'const double plutoT0 = {t0!r};\nconst double plutoStep = {STEP!r};\nconst int plutoCount = {N};\n'
    'const List<double> pluto = [\n' + body + '\n];\n')
print('vsop, moon (104 terms), pluto', N, 'samples')
